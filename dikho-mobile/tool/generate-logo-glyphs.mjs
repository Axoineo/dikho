#!/usr/bin/env node
// Turns the glyph paths in index.html, the single source of the animated mark,
// into Dart, so the app draws the same logo with nothing to fetch or decode.
//
//   node dikho-mobile/tool/generate-logo-glyphs.mjs

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const html = readFileSync(join(here, '../../index.html'), 'utf8')
const number = (n) => {
  const text = String(Math.round(n * 1000) / 1000)
  return text.includes('.') ? text : `${text}.0`
}

function dartFor(d) {
  const tokens = d.match(/[a-zA-Z]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?/g)
  const out = []
  let i = 0
  let x = 0
  let y = 0
  let startX = 0
  let startY = 0
  let command = ''
  const next = () => Number(tokens[i++])
  while (i < tokens.length) {
    if (/[a-zA-Z]/.test(tokens[i])) command = tokens[i++]
    const relative = command === command.toLowerCase()
    switch (command.toUpperCase()) {
      case 'M':
        x = (relative ? x : 0) + next()
        y = (relative ? y : 0) + next()
        startX = x
        startY = y
        out.push(`..moveTo(${number(x)}, ${number(y)})`)
        command = relative ? 'l' : 'L'
        break
      case 'L':
        x = (relative ? x : 0) + next()
        y = (relative ? y : 0) + next()
        out.push(`..lineTo(${number(x)}, ${number(y)})`)
        break
      case 'H':
        x = (relative ? x : 0) + next()
        out.push(`..lineTo(${number(x)}, ${number(y)})`)
        break
      case 'V':
        y = (relative ? y : 0) + next()
        out.push(`..lineTo(${number(x)}, ${number(y)})`)
        break
      case 'C': {
        const base = relative ? [x, y] : [0, 0]
        const v = [next(), next(), next(), next(), next(), next()]
        const p = v.map((value, index) => value + base[index % 2])
        out.push(`..cubicTo(${p.map(number).join(', ')})`)
        x = p[4]
        y = p[5]
        break
      }
      case 'Z':
        out.push('..close()')
        x = startX
        y = startY
        break
      default:
        throw new Error(`Unhandled path command ${command}`)
    }
  }
  return out
}

const parts = ['// Generated by tool/generate-logo-glyphs.mjs from index.html. Do not edit.', "import 'dart:ui';", '']
for (const [dart, id] of [['glyphD', 'dk-d'], ['glyphI', 'dk-i'], ['glyphK', 'dk-k'], ['glyphH', 'dk-h'], ['glyphO', 'dk-o'], ['glyphDot', 'dk-dot']]) {
  const match = new RegExp(`<path id="${id}" d="([^"]+)"`).exec(html)
  if (!match) throw new Error(`No path ${id} in index.html`)
  parts.push(`Path ${dart}() => Path()`, ...dartFor(match[1]).map((line) => `  ${line}`), '  ;', '')
}
writeFileSync(join(here, '../lib/features/splash/logo_glyphs.dart'), parts.join('\n').replace(/\n {2};\n/g, ';\n'))
